/* インラインSVG文字列を返す(innerHTML 用) */
export function icon(name, cls = '') {
  const paths = ICONS[name];
  if (!paths) return '';
  const body = paths.map((d) => (d.startsWith('F:')
    ? `<path class="f" d="${d.slice(2)}"/>`
    : `<path d="${d}"/>`)).join('');
  return `<svg class="ico${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${body}</svg>`;
}

/* 静的HTMLの <i data-ico="名前"></i> をまとめてSVGに置きかえる(起動時に1回) */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-ico]').forEach((el) => {
    el.innerHTML = icon(el.dataset.ico);
    el.removeAttribute('data-ico');
    el.classList.add('icw');
  });
}
