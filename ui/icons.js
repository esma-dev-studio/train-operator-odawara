/* 歯車: 8枚歯をプログラムで作る(手書きのパスより形が正確) */
function gearPath() {
  const pts = [];
  const N = 8, R1 = 9.6, R2 = 7.2;
  for (let i = 0; i < N; i++) {
    const a = (i / N) * Math.PI * 2;
    const w1 = 0.2, w2 = 0.33;   // 歯先・歯元の半角(ラジアン)
    [[a - w2, R2], [a - w1, R1], [a + w1, R1], [a + w2, R2]].forEach(([t, r]) => {
      pts.push(`${(12 + Math.cos(t) * r).toFixed(2)} ${(12 + Math.sin(t) * r).toFixed(2)}`);
    });
  }
  return 'M' + pts.join('L') + 'Z M15 12a3 3 0 1 1-6 0a3 3 0 1 1 6 0z';
}

